/* A sealed container, opened as a fixed recipient. */
#include "../src/sealed.h"
#include "fuzz_common.h"

int LLVMFuzzerTestOneInput(const uint8_t *data, size_t size)
{
	static const uint8_t xsk[32] = { 0x5d, 0xcb, 0x58, 0xe3, 0x0e, 0x51, 0x89, 0xc9, 0xbc, 0xa1, 0x2c,
					 0x8b, 0x93, 0xb5, 0xac, 0x8a, 0x9a, 0xd4, 0x7e, 0x99, 0x68, 0xe9,
					 0x08, 0xca, 0xca, 0x15, 0x53, 0x9e, 0xec, 0x16, 0xe9, 0xc3 };
	static const uint8_t rcpt[32] = { 0xf7, 0xaf, 0xdb, 0x94, 0xb0, 0x93, 0xe0, 0xeb, 0xa3, 0xff, 0xa9,
					  0xe5, 0xbc, 0xb3, 0xfa, 0x1d, 0xff, 0x7c, 0xf2, 0xf3, 0xdf, 0x9e,
					  0x3b, 0x10, 0x0f, 0xc5, 0x3d, 0x22, 0xa1, 0xec, 0xac, 0xeb };
	mor_sealed_open so;
	(void)mor_sealed_open_as(&so, data, size, rcpt, xsk, fuzz_arena());
	(void)mor_sealed_open_as(&so, data, size, NULL, xsk, fuzz_arena());
	return 0;
}
